import { Button as ButtonPrimitive } from "@base-ui/react/button"
import { cva, type VariantProps } from "class-variance-authority"
import { cn } from "cn"

/*
  El tamaño por defecto mide 44 px de alto, el mínimo táctil que exige el
  proyecto: el paciente usa esto sudando y entre series. shadcn genera este
  componente con 32 px, y por eso antes de la fase 2 había veintidós botones
  con un `min-h-11` pegado a mano y treinta y cinco que se habían quedado
  pequeños. `sm` y `xs` siguen existiendo para densidades donde el control no
  es el objetivo táctil principal (una barra de filtros de escritorio).

  Dentro de una cabecera —`PageHeader` y `SectionHeader` marcan su fila de
  acciones con `data-slot="header-actions"`— el botón se redondea del todo y la
  variante `ghost` recupera el borde: son las píldoras de borde fino que pide
  `docs/13-referencia-smart-fit.md` (1.6). La forma vive aquí y no en la
  cabecera porque cada pantalla construye sus propias acciones y ninguna
  debería tener que acordarse de pedirla.
*/
